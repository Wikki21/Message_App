-- =========================================================
-- MESSAGES
-- =========================================================

CREATE TABLE IF NOT EXISTS messages (
    id SERIAL PRIMARY KEY,

    partner_id INTEGER NOT NULL
        REFERENCES users(id)
        ON DELETE CASCADE,

    campaign_id INTEGER
        REFERENCES campaigns(id)
        ON DELETE SET NULL,

    customer_id INTEGER
        REFERENCES customers(id)
        ON DELETE SET NULL,

    phone VARCHAR(30) NOT NULL,

    template_name VARCHAR(255),

    message_id VARCHAR(500),

    status VARCHAR(50)
        DEFAULT 'pending',

    error TEXT,

    sent_at TIMESTAMP,

    delivered_at TIMESTAMP,

    failed_at TIMESTAMP,

    created_at TIMESTAMP NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMP NOT NULL
        DEFAULT CURRENT_TIMESTAMP
);



-- =========================================================
-- PARTNER PAYMENT SESSIONS
-- =========================================================
--
-- Created BEFORE partner account creation.
--
-- Payment flow:
--
--   Solo / Pro / Business
--        ↓
--   Razorpay subscription
--        ↓
--   payment_token
--        ↓
--   Payment verified
--        ↓
--   Create account allowed
--
-- IMPORTANT:
--
-- PAID payment is required before partner signup.
--
-- payment_token is generated by our backend.
--
-- status:
--   PENDING
--   PAID
--   FAILED
--   EXPIRED
--
-- used_at prevents the same payment from being
-- used to create multiple partner accounts.
-- =========================================================

CREATE TABLE IF NOT EXISTS partner_payment_sessions (
    id SERIAL PRIMARY KEY,

    payment_token VARCHAR(100) NOT NULL UNIQUE,

    plan_key VARCHAR(30) NOT NULL,

    plan_name VARCHAR(100) NOT NULL,

    razorpay_plan_id VARCHAR(100) NOT NULL,

    razorpay_subscription_id VARCHAR(100),

    razorpay_payment_id VARCHAR(100),

    razorpay_signature TEXT,

    amount INTEGER,

    currency VARCHAR(10)
        NOT NULL DEFAULT 'INR',

    status VARCHAR(30)
        NOT NULL DEFAULT 'PENDING'
        CHECK (
            status IN (
                'PENDING',
                'PAID',
                'FAILED',
                'EXPIRED'
            )
        ),

    created_at TIMESTAMP NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    paid_at TIMESTAMP,

    used_at TIMESTAMP
);



