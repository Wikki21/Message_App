-- =========================================================
-- PARTNER PROFILE CHANGE REQUESTS
-- =========================================================
--
-- Used AFTER partner account exists.
--
-- Partner may request:
--
--   name
--   company_name
--   phone
--   profile_photo
--   password
--
-- Partner CANNOT change:
--
--   email
--   role
--   is_active
--
-- Flow:
--
--   Partner Settings
--        ↓
--   Submit Changes
--        ↓
--   PENDING
--        ↓
--   Admin Profile Requests
--        ↓
--   APPROVE
--        ↓
--   users updated
-- =========================================================

CREATE TABLE IF NOT EXISTS partner_profile_requests (
    id SERIAL PRIMARY KEY,

    partner_id INTEGER NOT NULL
        REFERENCES users(id)
        ON DELETE CASCADE,

    requested_name VARCHAR(150) NOT NULL,

    requested_company_name VARCHAR(255),

    requested_phone VARCHAR(30),

    requested_profile_photo TEXT,

    requested_password_hash TEXT,

    status VARCHAR(20) NOT NULL
        DEFAULT 'PENDING'
        CHECK (
            status IN (
                'PENDING',
                'APPROVED',
                'REJECTED'
            )
        ),

    admin_id INTEGER
        REFERENCES users(id)
        ON DELETE SET NULL,

    admin_note TEXT,

    created_at TIMESTAMP NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    reviewed_at TIMESTAMP
);



