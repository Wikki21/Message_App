-- =========================================================
-- PARTNER WEBSITE SIGNUP APPLICATIONS
-- =========================================================
--
-- Website:
--
--   zaploft.in
--       ↓
--   Solo / Pro / Business
--       ↓
--   Razorpay
--       ↓
--   Payment verified
--       ↓
--   Create Account
--       ↓
--   This table
--       ↓
--   PENDING
--       ↓
--   Admin approval
--       ↓
--   users
--
-- Email CANNOT be changed by partner.
--
-- Password is stored as bcrypt hash.
-- =========================================================

CREATE TABLE IF NOT EXISTS partner_signup_requests (
    id SERIAL PRIMARY KEY,

    payment_session_id INTEGER
        REFERENCES partner_payment_sessions(id)
        ON DELETE SET NULL,

    payment_token VARCHAR(100),

    plan_key VARCHAR(30),

    plan_name VARCHAR(100) NOT NULL,

    name VARCHAR(150) NOT NULL,

    email VARCHAR(255) NOT NULL,

    password_hash TEXT NOT NULL,

    company_name VARCHAR(255) NOT NULL,

    phone VARCHAR(30),

    profile_photo TEXT,

    status VARCHAR(20) NOT NULL
        DEFAULT 'PENDING'
        CHECK (
            status IN (
                'PENDING',
                'APPROVED',
                'REJECTED'
            )
        ),

    admin_id INTEGER
        REFERENCES users(id)
        ON DELETE SET NULL,

    admin_note TEXT,

    created_at TIMESTAMP NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    reviewed_at TIMESTAMP
);


